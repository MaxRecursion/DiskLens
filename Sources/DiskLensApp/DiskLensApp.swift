import SwiftUI
import AppKit
import DiskLensCore

@main
enum Entry {
    static func main() {
        DatalessPolicy.disableMaterialization()   // never download cloud-only files while analysing
        let args = CommandLine.arguments
        #if DISKLENS_SNAPSHOTS
        if let i = args.firstIndex(of: "--snapshot"), i + 1 < args.count {
            MainActor.assumeIsolated { SnapshotRunner.run(outputDir: args[i + 1], demo: args.contains("--demo"), args: args) }
            return
        }
        #endif
        _ = args
        DiskLensApp.main()
    }
}

struct DiskLensApp: App {
    @State private var model = AppModel()
    @State private var scheduler = BackgroundScheduler()
    #if canImport(Sparkle)
    @State private var updater = SparkleUpdater()
    #endif

    init() {
        // Launched as a bare SwiftPM executable or .app: make sure we get a Dock icon and focus.
        NSApplication.shared.setActivationPolicy(.regular)
        DispatchQueue.main.async { NSApplication.shared.activate(ignoringOtherApps: true) }
    }

    var menuBarInserted: Binding<Bool> {
        Binding(get: { model.settings.menuBarEnabled && model.license.isEnabled(.scheduling) },
                set: { model.settings.menuBarEnabled = $0 })
    }

    var body: some Scene {
        Window("DiskLens", id: "main") {
            ContentView()
                .environment(model)
                .frame(minWidth: 1180, minHeight: 760)
                .preferredColorScheme(model.settings.appearance.colorScheme)
                .onAppear {
                    scheduler.start(model: model)
                    model.scheduledTick()
                }
        }
        .windowStyle(.hiddenTitleBar)
        .commands {
            CommandGroup(replacing: .appInfo) {
                Button("About DiskLens") { AboutPanel.show() }
                Button(model.license.state.isPaid ? "DiskLens Pro" : "Upgrade to DiskLens Pro…") { model.showPaywall(.settings) }
                    .disabled(model.license.state.isPaid)
                #if canImport(Sparkle)
                Button("Check for Updates…") { updater.checkForUpdates() }
                #endif
            }
            CommandGroup(replacing: .newItem) {
                Button("Scan Now") { model.startScan() }.keyboardShortcut("r", modifiers: .command)
                    .disabled(model.isScanning)
                Button("Cancel Scan") { model.cancelScan() }.keyboardShortcut(".", modifiers: .command)
                    .disabled(!model.isScanning)
            }
            CommandGroup(replacing: .help) {
                Button("DiskLens Help") { NSWorkspace.shared.open(AppLinks.support) }
                Button("Privacy Policy") { NSWorkspace.shared.open(AppLinks.privacy) }
                Divider()
                Button("Show Welcome Screen") { model.showOnboarding = true }
            }
        }

        Settings {
            SettingsView()
                .environment(model)
                .preferredColorScheme(model.settings.appearance.colorScheme)
        }

        MenuBarExtra(isInserted: menuBarInserted) {
            MenuBarContent().environment(model)
        } label: {
            MenuBarLabel(volume: model.volume)
        }
        .menuBarExtraStyle(.window)
    }
}

/// Template icon (adapts to the menu bar) plus measured free space.
struct MenuBarLabel: View {
    var volume: VolumeSnapshot?
    var body: some View {
        HStack(spacing: 3) {
            Image(nsImage: MenuBarIcon.image)
            if let v = volume { Text(String(format: "%.0f GB", Double(v.availableBytes) / 1e9)).monospacedDigit() }
        }
        .accessibilityLabel(volume.map { "DiskLens: \(ByteFormat.gb($0.availableBytes)) free" } ?? "DiskLens")
    }
}

enum MenuBarIcon {
    /// Loaded from the bundle (Resources/MenuBarIcon*.png, generated by scripts/tools/make_icon.swift)
    /// as a template image; falls back to an SF Symbol in bare SwiftPM builds.
    static let image: NSImage = {
        if let url = Bundle.main.url(forResource: "MenuBarIcon", withExtension: "png"), let img = NSImage(contentsOf: url) {
            if let url2 = Bundle.main.url(forResource: "MenuBarIcon@2x", withExtension: "png"), let rep = NSImageRep(contentsOf: url2) {
                rep.size = NSSize(width: 18, height: 18); img.addRepresentation(rep)
            }
            img.size = NSSize(width: 18, height: 18)
            img.isTemplate = true
            return img
        }
        let img = NSImage(systemSymbolName: "internaldrive", accessibilityDescription: "DiskLens") ?? NSImage()
        img.isTemplate = true
        return img
    }()
}

struct ContentView: View {
    @Environment(AppModel.self) private var model

    var body: some View {
        @Bindable var model = model
        VStack(spacing: 0) {
            SummaryHeader()
            Divider().opacity(0.4)
            HStack(spacing: 0) {
                Sidebar()
                    .frame(width: 210)
                Divider().opacity(0.4)
                Group {
                    if model.scan == nil && !model.isScanning {
                        EmptyStateView()
                    } else if model.isScanning && model.scan == nil {
                        ScanProgressView()
                    } else {
                        switch model.pane {
                        case .explorer: ExplorerView()
                        case .categories: CategoriesView()
                        case .largest: LargestFilesView()
                        case .cleanup: CleanupView()
                        case .reports: ReportsView()
                        case .manifest: ManifestView()
                        }
                    }
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            }
        }
        .background(Theme.background)
        .sheet(isPresented: $model.showPreview) { CleanupPreviewSheet() }
        .sheet(isPresented: $model.showOnboarding) { OnboardingView().environment(model) }
        .sheet(isPresented: Binding(get: { model.paywall != nil }, set: { if !$0 { model.paywall = nil } })) {
            if let c = model.paywall { PaywallView(context: c).environment(model) }
        }
        .alert("Move to Trash", isPresented: Binding(get: { model.trashResult != nil }, set: { if !$0 { model.trashResult = nil } })) {
            Button("OK") { model.trashResult = nil }
        } message: { Text(model.trashResult ?? "") }
    }
}

/// Colours for light and dark mode (resolved per appearance by AppKit).
enum Theme {
    static func dynamic(light: (Double, Double, Double), dark: (Double, Double, Double), alpha: Double = 1) -> Color {
        Color(nsColor: NSColor(name: nil) { appearance in
            let c = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: alpha)
        })
    }
    static let background = dynamic(light: (0.955, 0.96, 0.97), dark: (0.07, 0.075, 0.09))
    static let panel = dynamic(light: (0.925, 0.93, 0.945), dark: (0.11, 0.115, 0.135))
    static let card = dynamic(light: (1.0, 1.0, 1.0), dark: (0.14, 0.145, 0.17))
    static let treemapBackground = dynamic(light: (0.88, 0.89, 0.91), dark: (0.0, 0.0, 0.0), alpha: 0.6)
    static let accent = dynamic(light: (0.16, 0.42, 0.92), dark: (0.42, 0.62, 1.0))
    static let good = dynamic(light: (0.10, 0.58, 0.30), dark: (0.35, 0.85, 0.55))
    static let warn = dynamic(light: (0.78, 0.45, 0.0), dark: (1.0, 0.72, 0.3))
    static let bad = dynamic(light: (0.82, 0.18, 0.18), dark: (1.0, 0.42, 0.42))
    static let muted = Color(nsColor: .secondaryLabelColor)
}

struct Sidebar: View {
    @Environment(AppModel.self) private var model

    var body: some View {
        @Bindable var model = model
        VStack(alignment: .leading, spacing: 4) {
            Text("DISKLENS").font(.system(size: 11, weight: .heavy)).tracking(2).foregroundStyle(Theme.muted)
                .padding(.horizontal, 12).padding(.top, 14).padding(.bottom, 8)
            ForEach(Pane.allCases) { p in
                Button { model.pane = p } label: {
                    HStack(spacing: 10) {
                        Image(systemName: p.symbol).frame(width: 18)
                        Text(p.rawValue)
                        Spacer()
                        if p == .cleanup && !model.recommendations.isEmpty {
                            Text("\(model.recommendations.count)").font(.caption2.monospacedDigit())
                                .padding(.horizontal, 6).padding(.vertical, 1)
                                .background(Capsule().fill(Theme.accent.opacity(0.25)))
                        }
                    }
                    .padding(.horizontal, 12).padding(.vertical, 7)
                    .background(RoundedRectangle(cornerRadius: 7).fill(model.pane == p ? Theme.accent.opacity(0.22) : .clear))
                    .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .foregroundStyle(model.pane == p ? Color.primary : Color.primary.opacity(0.8))
                .accessibilityLabel(p.rawValue)
                .accessibilityAddTraits(model.pane == p ? .isSelected : [])
            }
            Spacer()
            VStack(alignment: .leading, spacing: 8) {
                Text(Platform.isSandboxed ? "Scan locations" : "Scan scope").font(.caption).foregroundStyle(Theme.muted)
                if Platform.isSandboxed {
                    SettingsLink {
                        Label(model.displayedGrants.isEmpty ? "Grant folders…" : "\(model.displayedGrants.count) folder(s) · Manage…", systemImage: "folder")
                    }
                } else {
                    Picker("Scan scope", selection: $model.scope) {
                        ForEach(ScanScope.allCases) { Text($0.rawValue).tag($0) }
                    }
                    .labelsHidden()
                    .disabled(model.isScanning)
                }
                if model.isScanning {
                    Button(role: .cancel) { model.cancelScan() } label: {
                        Label("Cancel Scan", systemImage: "stop.fill").frame(maxWidth: .infinity)
                    }
                    .controlSize(.large)
                } else {
                    Button { model.startScan() } label: {
                        Label(model.scan == nil ? "Scan" : "Rescan", systemImage: "arrow.clockwise").frame(maxWidth: .infinity)
                    }
                    .buttonStyle(.borderedProminent)
                    .controlSize(.large)
                }
                Text("Scans are read-only.").font(.caption2).foregroundStyle(Theme.muted)
                PlanChip()
            }
            .padding(12)
        }
        .background(Theme.panel)
    }
}

