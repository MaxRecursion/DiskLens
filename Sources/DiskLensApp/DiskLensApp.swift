struct ScanProgressView: View {
    @Environment(AppModel.self) private var model
    var body: some View {
        VStack(spacing: 14) {
            ProgressView().controlSize(.large)
            Text("Scanning (read-only)…").font(.title3.bold())
            if let p = model.progress {
                Text("Root \(p.rootIndex + 1) of \(p.rootCount): \(PathUtil.abbreviated(p.currentRoot))").foregroundStyle(Theme.muted)
                Text("\(p.filesVisited.formatted()) files · \(p.directoriesVisited.formatted()) folders · \(ByteFormat.string(p.bytesAllocated))")
                    .font(.body.monospacedDigit())
                Text(PathUtil.abbreviated(p.currentPath)).font(.caption.monospaced()).foregroundStyle(Theme.muted)
                    .lineLimit(1).truncationMode(.middle).frame(maxWidth: 700)
                if p.errors > 0 { Text("\(p.errors) unreadable entries (recorded as coverage gaps)").font(.caption).foregroundStyle(Theme.warn) }
            }
            Button("Cancel") { model.cancelScan() }
        }
        .padding(40)
    }
}

/// Sidebar footer: current plan and a quiet way to upgrade.
struct PlanChip: View {
    @Environment(AppModel.self) private var model
    var body: some View {
        let l = model.license
        HStack(spacing: 6) {
            Image(systemName: l.state.isPaid ? "checkmark.seal.fill" : "seal").foregroundStyle(l.state.isPaid ? Theme.good : Theme.accent)
            switch l.state {
            case .free: Text("Free plan").font(.caption)
            case .trial(let e): Text("Trial · \(max(0, Calendar.current.dateComponents([.day], from: Date(), to: e).day ?? 0)) days left").font(.caption)
            case .pro: Text(l.state.label).font(.caption.bold())
            }
            Spacer()
            if !l.state.isPaid { Button("Upgrade") { model.showPaywall(.settings) }.controlSize(.mini) }
        }
        .padding(.top, 4)
    }
}
